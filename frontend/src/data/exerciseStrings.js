export function exerciseStrings(lang) {
  const table = S[lang] || S.en;
  return (key, vars) => {
    let s = table[key] ?? S.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
}
